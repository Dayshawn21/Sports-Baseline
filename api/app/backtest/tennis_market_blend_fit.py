"""Fit the market-anchored tennis blend (26d) on the 2022 development season.

logit(p) = a * logit(de-vigged close) + b * logit(computed ELO), no intercept, one fit per
group, on 26c's eligible cases where the live gate keeps ELO. Holdout seasons never
reach the fit.

Data: Valuebetennis open data (https://www.valuebetennis.com), CC BY 4.0.

Run from api/: python -m app.backtest.tennis_market_blend_fit [--write]
"""
from __future__ import annotations

import argparse
from collections.abc import Iterable, Mapping
from dataclasses import dataclass
from pathlib import Path

import numpy as np

from app.backtest.tennis_closing_lines import (
    CHALLENGER_CATEGORIES, DATA_DIR, DEVELOPMENT_SEASONS, ClosingLineCase, build_cases, exclusion,
    load_valuebetennis,
)
from app.core.tennis_grading import PairedDifference, paired_loss_difference
from app.core.tennis_market_blend import BlendCoefficients, logit, market_anchored_prob

FIT_MODULE_PATH = Path(__file__).resolve().parents[1] / "core" / "tennis_market_blend_fit.py"
FIT_GROUPS = ("ATP", "WTA", "CHALLENGER")


def in_group(case: ClosingLineCase, group: str) -> bool:
    """26c's scored set for ATP and WTA; its Challenger set, both tours pooled, for CHALLENGER."""
    if group == "CHALLENGER":
        return exclusion(case, CHALLENGER_CATEGORIES) is None
    return case.tour == group and exclusion(case) is None


def development_cases(cases: Iterable[ClosingLineCase], group: str) -> list[ClosingLineCase]:
    return [c for c in cases if c.season in DEVELOPMENT_SEASONS and in_group(c, group)]


@dataclass(frozen=True)
class FitResult:
    n: int
    coefficients: BlendCoefficients
    market_se: float
    elo_se: float


def _newton_logistic(x: np.ndarray, y: np.ndarray, tol: float = 1e-10, max_iter: int = 50) -> tuple[np.ndarray, np.ndarray]:
    """Unpenalized, intercept-free logistic regression: (coefficients, information matrix X'WX)."""
    beta = np.zeros(x.shape[1])
    for _ in range(max_iter):
        p = 1 / (1 + np.exp(-x @ beta))
        information = x.T @ (x * (p * (1 - p))[:, None])
        step = np.linalg.solve(information, x.T @ (y - p))
        beta = beta + step
        if np.max(np.abs(step)) < tol:
            break
    else:
        raise RuntimeError("logistic fit did not converge")
    p = 1 / (1 + np.exp(-x @ beta))
    return beta, x.T @ (x * (p * (1 - p))[:, None])


def fit_group(cases: Iterable[ClosingLineCase]) -> FitResult:
    """Maximum likelihood on development cases with a reliable ELO; anything else is dropped here."""
    rows = [c for c in cases if c.season in DEVELOPMENT_SEASONS and c.elo_reliable]
    if len(rows) < 3:
        raise ValueError(f"too few reliable development cases to fit ({len(rows)})")
    x = np.array([[logit(c.market_prob), logit(c.elo_prob)] for c in rows])  # type: ignore[arg-type]
    y = np.array([c.p1_won for c in rows], dtype=float)
    beta, information = _newton_logistic(x, y)
    se = np.sqrt(np.diag(np.linalg.inv(information)))
    return FitResult(len(rows), BlendCoefficients(float(beta[0]), float(beta[1])), float(se[0]), float(se[1]))


def served_prob(case: ClosingLineCase, coefs: BlendCoefficients) -> float | None:
    """What the app would serve: the market alone when the live gate drops ELO."""
    if case.market_prob is None:
        return None
    return market_anchored_prob(coefs, case.market_prob, case.elo_prob if case.elo_reliable else None)


def in_sample_differences(
    cases: list[ClosingLineCase], coefs: BlendCoefficients,
) -> tuple[PairedDifference, PairedDifference]:
    """(fitted minus the close, fitted minus the hand-set blend), over every eligible case."""
    scored = [c for c in cases if c.market_prob is not None and c.blend_prob is not None]
    fitted = [served_prob(c, coefs) for c in scored]
    outcomes = [c.p1_won for c in scored]
    return (
        paired_loss_difference(fitted, [c.market_prob for c in scored], outcomes),  # type: ignore[arg-type,misc]
        paired_loss_difference(fitted, [c.blend_prob for c in scored], outcomes),  # type: ignore[arg-type,misc]
    )


def render_module(fits: Mapping[str, FitResult]) -> str:
    lines = [
        '"""Generated by `python -m app.backtest.tennis_market_blend_fit --write`. Do not edit.',
        "",
        "Market-anchored blend coefficients (26d), fitted on the Valuebetennis development",
        "season(s) below against the de-vigged Pinnacle close and computed ELO. Regenerating",
        "this file is a new ensemble model version.",
        '"""',
        "from __future__ import annotations",
        "",
        "from app.core.tennis_market_blend import BlendCoefficients",
        "",
        f"FIT_SEASONS: tuple[int, ...] = {tuple(sorted(DEVELOPMENT_SEASONS))!r}",
        "FIT_COEFFICIENTS: dict[str, BlendCoefficients] = {",
    ]
    for group in sorted(fits):
        c = fits[group].coefficients
        lines.append(f"    {group!r}: BlendCoefficients(market={c.market:.6f}, elo={c.elo:.6f}),")
    lines += ["}", "FIT_SIZES: dict[str, int] = {"]
    lines += [f"    {group!r}: {fits[group].n}," for group in sorted(fits)]
    lines.append("}")
    return "\n".join(lines) + "\n"


def report(cases: list[ClosingLineCase], fits: Mapping[str, FitResult]) -> str:
    lines = [
        f"Tennis market-anchored blend fit (26d) - development seasons {sorted(DEVELOPMENT_SEASONS)}",
        "  Data: Valuebetennis open data (valuebetennis.com), CC BY 4.0. Pinnacle closing odds.",
        "  logit(p) = a * logit(close) + b * logit(elo (computed)), no intercept; fit on reliable-ELO cases.",
        "  Holdout seasons are never read by the fit.",
        "",
        "Coefficients (+/- one standard error)",
    ]
    for group in FIT_GROUPS:
        f = fits[group]
        lines.append(
            f"  {group:<11}n={f.n:<6} a (market) {f.coefficients.market:.4f} +/- {f.market_se:.4f}"
            f"   b (elo) {f.coefficients.elo:+.4f} +/- {f.elo_se:.4f}"
        )
    lines += ["", "In-sample paired log-loss difference (development only, NOT a verdict; gated cases served as the market)"]
    for group in FIT_GROUPS:
        eligible = development_cases(cases, group)
        vs_close, vs_blend = in_sample_differences(eligible, fits[group].coefficients)
        lines.append(
            f"  {group:<11}n={vs_close.n:<6} vs close {vs_close.mean:+.4f} +/- {vs_close.standard_error or 0.0:.4f}"
            f"   vs hand-set blend {vs_blend.mean:+.4f} +/- {vs_blend.standard_error or 0.0:.4f}"
        )
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description="Fit the 26d market-anchored tennis blend on the development season")
    parser.add_argument("--write", action="store_true", help=f"write {FIT_MODULE_PATH.name}")
    parser.add_argument("--data-dir", type=Path, default=DATA_DIR)
    args = parser.parse_args()
    matches, _ = load_valuebetennis(args.data_dir)
    cases = [c for c in build_cases(matches) if c.season in DEVELOPMENT_SEASONS]
    fits = {group: fit_group(development_cases(cases, group)) for group in FIT_GROUPS}
    print(report(cases, fits))
    if args.write:
        FIT_MODULE_PATH.write_text(render_module(fits), encoding="utf-8")
        print(f"\nWrote {FIT_MODULE_PATH}")


if __name__ == "__main__":
    main()
