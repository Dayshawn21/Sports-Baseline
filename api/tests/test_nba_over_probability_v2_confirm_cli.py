SCORED_AT = dt.datetime(2026, 11, 17, 15, 0, tzinfo=dt.UTC)


class _Session:
    async def __aenter__(self):
        return object()

    async def __aexit__(self, *exc):
        return False


def _patch_db(monkeypatch, finished):
    calls = []

    async def progress(db, season, weeks):
        calls.append("progress")
        return {1: (43, 43), 2: (49, 49), 3: (54, 54), 4: (51, 20)}

    async def finished_weeks(db, season):
        calls.append("finished")
        return set(finished)

    async def forbidden(*args):
        calls.append("box scores")
        raise AssertionError("box scores must not be read before the gate opens")

    monkeypatch.setattr(pool, "SessionLocal", _Session)
    monkeypatch.setattr(nba, "get_week_progress", progress)
    monkeypatch.setattr(nba, "get_finished_weeks", finished_weeks)
    monkeypatch.setattr(nba, "get_week_game_ids", forbidden)
    monkeypatch.setattr(nba, "get_projection_history", forbidden)
    return calls


def _result(verdict="show", worst_gap=0.03, cases=2500):
    return ConfirmationResult(
        family="scaled_normal", cases=cases, pairs=12000, ece=0.012, worst_gap=worst_gap,
        brier=0.187, normal_brier=0.188, verdict=verdict,
    )


def test_loads_every_stored_season_and_scores_only_2026():
    assert confirm.LOADED_SEASONS == (2023, 2024, 2025, 2026)


def test_score_before_the_gate_opens_stops_without_reading_box_scores(monkeypatch, tmp_path, capsys):
    calls = _patch_db(monkeypatch, finished={1, 2, 3})
    confirm.main(["--score"], result_path=tmp_path / "result.py")
    out = capsys.readouterr().out
    assert calls == ["progress", "finished"]
    assert "State: accruing" in out
    assert "nothing scored, no box score read" in out
    assert not (tmp_path / "result.py").exists()


def test_gate_mode_never_reads_box_scores_even_when_ready(monkeypatch, tmp_path, capsys):
    calls = _patch_db(monkeypatch, finished={1, 2, 3, 4})
    confirm.main([], result_path=tmp_path / "result.py")
    assert calls == ["progress", "finished"]
    assert "State: ready" in capsys.readouterr().out


def test_score_refuses_once_a_confirmation_is_recorded(monkeypatch, tmp_path):
    calls = _patch_db(monkeypatch, finished={1, 2, 3, 4})
    recorded = tmp_path / "result.py"
    recorded.write_text("SHOWN_MARKETS = frozenset()\n", encoding="utf-8")
    with pytest.raises(SystemExit):
        confirm.main(["--score"], result_path=recorded)
    assert calls == []


