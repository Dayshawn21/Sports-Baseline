def test_report_format():
    case = NbaReplayCase(
        player_id=1, game_id=7, game_date=dt.date(2026, 10, 21), game_type="REG",
        market="points", prior_minutes=30.0, projection=20.4, actual=20.0,
    )
    results = {"points": _result(), "rebounds": _result("hide", worst_gap=0.071)}
    text = confirm.report(results, [case], {7: 1, 8: 2}, PARAMS_BY_MARKET)
    lines = text.splitlines()
    assert lines[0] == "NBA over probability nba-pover-v2: one confirmation on 2026 weeks 1-4"
    assert "2025-26 cases scored: 0" in lines[1]
    assert "ebd4aea" in lines[1]
    assert re.search(r"^  points\s+scaled_normal\s+2500\s+12000\s+0\.012\s+0\.030\s+0\.1870\s+0\.1880  show\s*$", text, re.M)
    assert re.search(r"^  rebounds\s+.*hide\s+worst gap$", text, re.M)
    assert re.search(r"^  points_assists\s+no cases$", text, re.M)
    assert re.search(r"^  blocks\s+not_carried \(44a\)$", text, re.M)
    assert "  week 1: 1 games, 1 cases" in lines
    assert "  week 2: 1 games, 0 cases" in lines
    assert re.search(r"^  points\s+\d+\s+[\d.]+\s+[\d.]+$", text, re.M)


def test_rendered_module_round_trips():
    results = {"points": _result(), "rebounds": _result("hide", worst_gap=None, cases=250)}
    source = confirm.render_module(results, SCORED_AT)
    assert source.startswith(
        '"""Generated by `python -m app.backtest.nba_over_probability_v2_confirm --score`. Do not edit.'
    )
    assert 'SCORED_AT = "2026-11-17T15:00:00+00:00"' in source
    assert "SHOWN_MARKETS: frozenset[str] = frozenset({'points'})" in source
    namespace: dict[str, object] = {}
    exec(source, namespace)
    assert namespace["RESULTS"] == results
    assert namespace["SHOWN_MARKETS"] == {"points"}
    # A carried market with no result is hidden, never shown by omission.
    assert namespace["HIDDEN_MARKETS"] == set(PARAMS_BY_MARKET) - {"points"}
    assert namespace["NOT_CARRIED"] == {"blocks", "threes_made"}
    assert namespace["CONFIRMATION_WEEKS"] == (1, 2, 3, 4)


def test_rendered_module_with_nothing_shown():
    source = confirm.render_module({"points": _result("hide")}, SCORED_AT)
    assert "SHOWN_MARKETS: frozenset[str] = frozenset()" in source


def _replays(monkeypatch, frozen_from_fit: bool):
    """Synthetic 2024 and 2026 replays; the frozen params are refit from 2024 unless drift is wanted."""
    import random

    from app.core import nba_projection_backtest
    from app.core.nba_over_probability_v2_confirmation_score import refit

    rng = random.Random(3)

    def cases(season, game_ids, n):
        return [
            NbaReplayCase(
                player_id=i, game_id=game_ids[i % len(game_ids)], game_date=dt.date(season, 11, 1), game_type="REG",
                market=market, prior_minutes=30.0, projection=mean,
                actual=float(max(0, round(rng.gauss(mean, (4 + 2 * mean) ** 0.5)))),
            )
            for i in range(n)
            for market, mean in (("points", 18.0), ("rebounds", 7.0))
        ]

    by_season = {2024: cases(2024, [100], 800), 2026: cases(2026, [1, 2, 3, 4, 99], 1000)}
    monkeypatch.setattr(nba_projection_backtest, "replay_cases", lambda history, season, arm: by_season[season])
    shape = {"points": PARAMS_BY_MARKET["points"], "rebounds": PARAMS_BY_MARKET["rebounds"]}
    frozen = refit(shape, by_season[2024]) if frozen_from_fit else shape
    monkeypatch.setattr(confirm, "PARAMS_BY_MARKET", frozen)


def _patch_ready(monkeypatch):
    calls = _patch_db(monkeypatch, finished={1, 2, 3, 4})

    async def game_ids(db, season, weeks):
        calls.append("game ids")
        return {1: 1, 2: 2, 3: 3, 4: 4}

    async def history(db, seasons):
        calls.append(("history", tuple(seasons)))
        return []

    monkeypatch.setattr(nba, "get_week_game_ids", game_ids)
    monkeypatch.setattr(nba, "get_projection_history", history)
    return calls


def test_score_when_ready_writes_the_result_module(monkeypatch, tmp_path, capsys):
    calls = _patch_ready(monkeypatch)
    _replays(monkeypatch, frozen_from_fit=True)
    result_path = tmp_path / "result.py"
    confirm.main(["--score"], result_path=result_path)
    assert calls == ["progress", "finished", "game ids", ("history", (2023, 2024, 2025, 2026))]
    out = capsys.readouterr().out
    # Game 99 is outside weeks 1-4, so 800 of the 1,000 players per market are scored.
    assert re.search(r"^  points\s+scaled_normal\s+800\s", out, re.M)
    assert re.search(r"^  rebounds\s+negbin\s+800\s", out, re.M)
    assert "points_assists" not in out
    namespace: dict[str, object] = {}
    exec(result_path.read_text(encoding="utf-8"), namespace)
    assert set(namespace["RESULTS"]) == {"points", "rebounds"}
    assert namespace["SHOWN_MARKETS"] | namespace["HIDDEN_MARKETS"] == {"points", "rebounds"}


def test_score_stops_on_drift_without_writing(monkeypatch, tmp_path):
    _patch_ready(monkeypatch)
    _replays(monkeypatch, frozen_from_fit=False)
    result_path = tmp_path / "result.py"
    with pytest.raises(SystemExit, match="no longer reproduces the frozen parameters"):
        confirm.main(["--score"], result_path=result_path)
    assert not result_path.exists()
