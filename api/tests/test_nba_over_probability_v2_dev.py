def _cases(market, n, seed):
    rng = np.random.default_rng(seed)
    means = rng.uniform(0.6, 3.0, n)
    actuals = rng.negative_binomial(2.0, 2.0 / (2.0 + means))
    start = dt.date(2024, 10, 21)
    return [
        NbaReplayCase(
            player_id=i, game_id=i, game_date=start + dt.timedelta(days=i % 160), game_type="REG",
            market=market, prior_minutes=30.0, projection=float(m), actual=float(a),
        )
        for i, (m, a) in enumerate(zip(means, actuals))
    ]


