const { chromium } = require(process.env.PLAYWRIGHT_MODULE)
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
async function main() {
 const browser = await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true})
 const results = {checks:[],errors:[]}
 try {
  for (const width of [1440,390]) {
   const page = await browser.newPage({viewport:{width,height:1000},reducedMotion:'reduce'})
   page.on('pageerror',e=>results.errors.push(e.message))
   await page.goto('http://localhost:3001/#/nfl/game/94')
   const props=page.getByRole('tab',{name:'Player Props',exact:true}), matchup=page.getByRole('tab',{name:'Matchup',exact:true})
   await props.waitFor()
   assert.equal(await props.getAttribute('aria-selected'),'true')
   const panel=page.getByRole('tabpanel')
   await panel.getByRole('region',{name:'Player usage',exact:true}).waitFor()
   await panel.locator('section[aria-label="Receiving yards lines"] button.prop-table__open').first().waitFor()
   assert.equal(await panel.locator('section[aria-label="Team stats"]').count(),0)
   assert.equal(await panel.locator('section[aria-label="Position production allowed"]').count(),0)
   const hero=await page.locator('.nfl-game-hero').innerText()
   await page.screenshot({path:path.join(__dirname,`tabs-${width}-props.png`)})
   const trigger=panel.locator('section[aria-label="Receiving yards lines"] button.prop-table__open').first()
   await trigger.click()
   await page.locator('.ant-drawer-body .nfl-evidence-context__opponent').waitFor()
   await page.keyboard.press('Escape')
   await page.locator('.ant-drawer-body .nfl-prop-detail').waitFor({state:'hidden'})
   await props.focus()
   await page.keyboard.press('ArrowLeft')
   await page.keyboard.press('Enter')
   await page.locator('.nfl-game-tabs [data-node-key="matchup"] [aria-selected="true"]').waitFor()
   await panel.locator('section[aria-label="Team stats"]').waitFor()
   await panel.locator('section[aria-label="Position production allowed"]').waitFor()
   assert.equal(await panel.locator('section[aria-label="Player usage"]').count(),0)
   assert.equal(await panel.locator('button.prop-table__open').count(),0)
   assert.equal(await page.locator('.nfl-game-hero').innerText(),hero)
   await page.screenshot({path:path.join(__dirname,`tabs-${width}-matchup.png`)})
   assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
   await props.click()
   await panel.locator('section[aria-label="Player usage"]').waitFor()
   assert.equal(await page.locator('.ant-drawer-body .nfl-prop-detail:visible').count(),0)
   assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
   await matchup.click()
   await page.goto('http://localhost:3001/#/nfl/game/95')
   await page.locator('.nfl-game-tabs [data-node-key="props"] [aria-selected="true"]').waitFor()
   results.checks.push({width,defaultProps:true,separation:true,sharedHeader:true,drawerContext:true,keyboardSwitch:true,noOverflow:true,noResurrectedDrawer:true,gameResetsToProps:true})
   await page.close()
  }
  assert.deepEqual(results.errors,[])
 } finally { await browser.close(); fs.writeFileSync(path.join(__dirname,'tabs-browser.json'),JSON.stringify(results,null,2)) }
 console.log(JSON.stringify(results))
}
main().catch(e=>{console.error(e);process.exitCode=1})
